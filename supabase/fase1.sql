-- ---------- Parcelas: uma linha por parcela, no mês em que cai ----------
-- "valor" é sempre o total da compra. Cada parcela = total / parcelas,
-- e a última absorve os centavos. Ex.: R$ 1.000 em 3x = 333,33 + 333,33 + 333,34.
-- security_invoker: a view respeita o RLS (cada um só vê as próprias parcelas).
create or replace view public.v_parcelas with (security_invoker = true) as
select
  l.id                                                  as lancamento_id,
  l.user_id,
  l.tipo,
  l.categoria,
  l.descricao,
  l.pagamento,
  l.data::date                                          as data_compra,
  (l.data::date + make_interval(months => n - 1))::date as data,
  date_trunc('month', l.data::date + make_interval(months => n - 1))::date as mes,
  n                                                     as parcela,
  l.parcelas                                            as total_parcelas,
  l.valor::numeric                                      as valor_total,
  case when n = l.parcelas
       then l.valor::numeric - round(l.valor::numeric / l.parcelas, 2) * (l.parcelas - 1)
       else round(l.valor::numeric / l.parcelas, 2)
  end                                                   as valor
from public.lancamentos l
cross join lateral generate_series(1, l.parcelas) as n;

revoke all on public.v_parcelas from anon;
grant select on public.v_parcelas to authenticated;

-- ---------- Histórico antigo vira seu + suas categorias ----------
do $$
declare
  email_dono text := 'SEU_EMAIL@exemplo.com';   -- >>> TROQUE PELO SEU E-MAIL <<<
  id_dono    uuid;
begin
  select id into id_dono from auth.users where lower(email) = lower(email_dono);
  if id_dono is null then
    raise exception 'O e-mail % ainda não está em Authentication > Users. Convide-o primeiro.', email_dono;
  end if;

  update public.lancamentos set user_id = id_dono where user_id is null;

  insert into public.categorias (user_id, nome, tipo)
  select id_dono, c.nome, c.tipo
  from (
    select unnest(array['Cabelo','Carro','Compras','iFood','Júlia','Saídas','Uber']) as nome, 'Despesa' as tipo
    union
    select unnest(array['BASF','Ivan','MX','VR']), 'Receita'
    union
    select distinct categoria, tipo from public.lancamentos
     where user_id = id_dono and tipo in ('Despesa', 'Receita') and length(trim(coalesce(categoria, ''))) > 0
  ) c
  on conflict do nothing;
end
$$;
