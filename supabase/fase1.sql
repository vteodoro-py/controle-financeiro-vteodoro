-- ---------- Lançamentos: quem lançou e quando ----------
alter table public.lancamentos
  add column if not exists created_at    timestamptz not null default now(),
  add column if not exists user_id       uuid references auth.users(id),
  add column if not exists atualizado_em timestamptz;

alter table public.lancamentos alter column user_id set default auth.uid();

update public.lancamentos set parcelas = 1 where parcelas is null or parcelas < 1;

create index if not exists lancamentos_user_data_idx on public.lancamentos (user_id, data);

-- O dono nunca muda e a data de edição é preenchida sozinha.
create or replace function public.lancamentos_ao_salvar()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    new.user_id := coalesce(new.user_id, auth.uid());
  else
    if old.user_id is not null then
      new.user_id := old.user_id;
    end if;
    new.atualizado_em := now();
  end if;
  return new;
end
$$;

drop trigger if exists ao_salvar on public.lancamentos;
create trigger ao_salvar before insert or update on public.lancamentos
  for each row execute function public.lancamentos_ao_salvar();

-- ---------- Categorias: cada pessoa tem as suas ----------
create table if not exists public.categorias (
  id        bigint generated by default as identity primary key,
  user_id   uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nome      text not null check (length(trim(nome)) > 0),
  tipo      text not null check (tipo in ('Despesa', 'Receita')),
  ativa     boolean not null default true,
  criado_em timestamptz not null default now()
);

create unique index if not exists categorias_unica
  on public.categorias (user_id, tipo, lower(nome));

-- ---------- Segurança: cada um só enxerga o que é seu ----------
-- Remove as políticas antigas (inclusive a que liberava a chave anon).
do $$
declare p record;
begin
  for p in
    select policyname, tablename from pg_policies
    where schemaname = 'public' and tablename in ('lancamentos', 'categorias')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end
$$;

alter table public.lancamentos enable row level security;
